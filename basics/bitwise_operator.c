#include <stdio.h>

int main()
{
    printf("Bitwise AND(&): %d\n",5&3);
    printf("Bitwise OR(|): %d\n",5|3);
    printf("Bitwise XOR(^): %d\n",5^3);
    printf("Bitwise NOT(~): %d\n",~1);
    printf("Bitwise LEFT SHIFT(<<): %d\n",5<<1);
    printf("Bitwise RIGHT SHIFT(>>): %d\n",10>>1);
}